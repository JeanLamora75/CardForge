/** UI locale is presentation-only; never store it in game state or save envelopes. */
export type Locale = "fr" | "en";
export interface LanguageStore {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}
export const LANGUAGE_KEY = "cardforge.language.v1";
export const SUPPORTED_LOCALES: readonly Locale[] = ["fr", "en"];
export function resolveLanguage(preferred: string | readonly string[] | null | undefined): Locale {
  const values = Array.isArray(preferred) ? preferred : [preferred];
  for (const item of values) {
    if (typeof item !== "string") continue;
    const short = item.trim().toLowerCase().split(/[-_]/)[0];
    if (short === "fr" || short === "en") return short;
  }
  return "en";
}
export function readLanguage(store: LanguageStore | null, browserLanguages: readonly string[] = []): Locale {
  if (store) {
    try {
      const saved = store.getItem(LANGUAGE_KEY);
      if (saved === "fr" || saved === "en") return saved;
    } catch { /* Private browsing may deny storage. */ }
  }
  return resolveLanguage(browserLanguages);
}
export function saveLanguage(store: LanguageStore | null, locale: Locale): boolean {
  if (!store || !SUPPORTED_LOCALES.includes(locale)) return false;
  try { store.setItem(LANGUAGE_KEY, locale); return true; }
  catch { return false; }
}

