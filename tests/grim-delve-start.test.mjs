import test from 'node:test';
import assert from 'node:assert/strict';
import { grimDelveEngine, GRIM_DELVE_RULES_VERSION } from '../src/games/clear-the-dungeon/engine.ts';
import { makeDeckWithJokers } from '../src/core/cards.ts';

const allIds = makeDeckWithJokers().map(card=>card.id).sort();
const owned = s => [...s.columns.flat(), ...s.drawPile, ...s.hand, ...s.damages, ...s.defeated, ...s.removed];

test('Classic configuration is fixed and has no Advanced or reserve option',()=>{
 assert.equal(GRIM_DELVE_RULES_VERSION,'classic-1.1.0');
 assert.throws(()=>grimDelveEngine.createInitialState({seed:12, mode:'advanced'}));
 assert.throws(()=>grimDelveEngine.createInitialState({seed:12, reserve:true}));
});
test('CTD-T10: 54 physical cards distribute as 12 monsters plus 39 draw + 3 hand',()=>{
 const s=grimDelveEngine.createInitialState({seed:123});
 assert.equal(s.columns.length,4);
 assert.ok(s.columns.every(col=>col.length===3));
 assert.ok(s.columns.flat().every(id=> /^(hearts|diamonds|clubs|spades)-(11|12|13)$/.test(id)));
 assert.equal(s.drawPile.length,39);
 assert.equal(s.hand.length,3);
 assert.equal(s.damages.length,0);
 assert.equal(s.defeated.length,0);
 assert.equal(s.removed.length,0);
 assert.deepEqual(owned(s).sort(),allIds);
 assert.deepEqual(s.visibleMonsters,s.columns.map(col=>col[0]));
 assert.equal(s.phase,'attack');
 assert.equal(s.outcome,'in-progress');
 assert.equal(grimDelveEngine.validateState(s).valid,true);
});
test('same seed reproduces all ordered zones and other seeds change order',()=>{
 const a=grimDelveEngine.createInitialState({seed:42});
 assert.deepEqual(a,grimDelveEngine.createInitialState({seed:42}));
 assert.notDeepEqual(a,grimDelveEngine.createInitialState({seed:43}));
});
test('jokers remain distinct in power cards with no monsters or extra cards',()=>{
 const s=grimDelveEngine.createInitialState({seed:17});
 assert.deepEqual([...s.hand,...s.drawPile].filter(id=>id.startsWith('joker-')).sort(),['joker-1','joker-2']);
 assert.deepEqual(s.columns.flat().filter(id=>id.startsWith('joker-')),[]);
});
test('CTD-T43: first legal actions are generated by engine; discard one card without changing input',()=>{
 const s=grimDelveEngine.createInitialState({seed:5});
 const actions=grimDelveEngine.getLegalActions(s);
 assert.deepEqual(actions.filter(action=>action.type==='discard'), s.hand.map(cardId=>({type:'discard',cardId})));
 const result=grimDelveEngine.transition(s,actions[0]);
 assert.equal(result.accepted,true);
 assert.equal(result.state.hand.length,2);
 assert.deepEqual(result.state.damages,[s.hand[0]]);
 assert.equal(s.hand.length,3);
 assert.equal(s.damages.length,0);
 assert.equal(grimDelveEngine.validateState(result.state).valid,true);
});
test('CTD-T41 / CTD-T128 / CTD-T135: new hand cannot start before all three cards used or discarded',()=>{
 const s=grimDelveEngine.createInitialState({seed:8});
 assert.equal(grimDelveEngine.transition(s,{type:'end-hand'}).accepted,false);
 assert.deepEqual(grimDelveEngine.getLegalActions(s).filter(x=>x.type==='end-hand'),[]);
});
test('CTD-T46 / CTD-T61 / CTD-T134: after emptying hand, explicit end-hand draws next three and preserves order',()=>{
 let s=grimDelveEngine.createInitialState({seed:70});
 const firstDraw=s.drawPile.slice(0,3);
 for(const cardId of [...s.hand]) s=grimDelveEngine.transition(s,{type:'discard',cardId}).state;
 assert.deepEqual(grimDelveEngine.getLegalActions(s),[{type:'end-hand'}]);
 const t=grimDelveEngine.transition(s,{type:'end-hand'});
 assert.equal(t.accepted,true);
 assert.deepEqual(t.state.hand,firstDraw);
 assert.deepEqual(t.state.drawPile,s.drawPile.slice(3));
 assert.equal(grimDelveEngine.validateState(t.state).valid,true);
});
test('invalid actions preserve exact previous state and no phantom cards',()=>{
 const s=grimDelveEngine.createInitialState({seed:6});
 const invalid=grimDelveEngine.transition(s,{type:'discard',cardId:'joker-absent'});
 assert.equal(invalid.accepted,false);
 assert.strictEqual(invalid.state,s);
 assert.deepEqual(owned(s).sort(),allIds);
});
test('validator rejects duplicate, missing, malformed and altered face-up monster',()=>{
 const s=grimDelveEngine.createInitialState({seed:30});
 const copy=structuredClone(s); copy.hand[0]=copy.hand[1];
 assert.equal(grimDelveEngine.validateState(copy).valid,false);
 const missing=structuredClone(s);missing.drawPile.pop();
 assert.equal(grimDelveEngine.validateState(missing).valid,false);
 const visible=structuredClone(s);visible.visibleMonsters[0]=visible.columns[0][1];
 assert.equal(grimDelveEngine.validateState(visible).valid,false);
 assert.equal(grimDelveEngine.validateState({hello:'world'}).valid,false);
});
test('CTD-T22 / CTD-T58 / CTD-T126 / CTD-T138: seventh damage causes immediate loss and no subsequent legal actions',()=>{
 let s=grimDelveEngine.createInitialState({seed:20});
 for(let i=0;i<6;i++){
   if(s.hand.length===0) s=grimDelveEngine.transition(s,{type:'end-hand'}).state;
   s=grimDelveEngine.transition(s,{type:'discard',cardId:s.hand[0]}).state;
 }
 if(s.hand.length===0) s=grimDelveEngine.transition(s,{type:'end-hand'}).state;
 s=grimDelveEngine.transition(s,{type:'discard',cardId:s.hand[0]}).state;
 assert.equal(grimDelveEngine.getOutcome(s),'loss');
 assert.deepEqual(grimDelveEngine.getLegalActions(s),[]);
 assert.equal(grimDelveEngine.transition(s,{type:'end-hand'}).accepted,false);
});
